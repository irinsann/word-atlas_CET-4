export const singlePos = new Map();
function pos(tag, words) {
  for (const w of words.split(/\s+/).filter(Boolean)) {
    if (singlePos.has(w)) throw Error(`Duplicate POS ${w}`);
    singlePos.set(w, tag);
  }
}
